const $=(s,c=document)=>c.querySelector(s);
const $$=(s,c=document)=>[...c.querySelectorAll(s)];

/* ---------- i18n ---------- */
function setLang(lang){
  const dict=I18N[lang]||I18N.ro;
  $$("[data-i18n]").forEach(el=>{
    const k=el.getAttribute("data-i18n");
    if(!(k in dict))return;
    if(el.tagName==="META")el.setAttribute("content",dict[k]);
    else el.textContent=dict[k];
  });
  document.documentElement.lang=lang;
  $("#langCurrent").textContent=lang.toUpperCase();
  $$("#langMenu button").forEach(b=>b.classList.toggle("active",b.dataset.lang===lang));
  try{localStorage.setItem("ce_lang",lang);}catch(e){}
}

/* ---------- counters ---------- */
function animateCount(el){
  const target=+el.dataset.count, suffix=el.dataset.suffix||"";
  const dur=1400, t0=performance.now();
  function step(t){
    const p=Math.min((t-t0)/dur,1);
    const eased=1-Math.pow(1-p,3);
    el.textContent=Math.round(target*eased)+suffix;
    if(p<1)requestAnimationFrame(step);
  }
  requestAnimationFrame(step);
}

/* ---------- init ---------- */
document.addEventListener("DOMContentLoaded",()=>{
  // language
  let saved="ro";
  try{saved=localStorage.getItem("ce_lang")||"ro";}catch(e){}
  setLang(saved);

  const langBtn=$("#langBtn"),langMenu=$("#langMenu");
  langBtn.addEventListener("click",e=>{e.stopPropagation();
    const open=langMenu.classList.toggle("open");langBtn.setAttribute("aria-expanded",open);});
  document.addEventListener("click",()=>{langMenu.classList.remove("open");langBtn.setAttribute("aria-expanded","false");});
  $$("#langMenu button").forEach(b=>b.addEventListener("click",()=>{setLang(b.dataset.lang);langMenu.classList.remove("open");}));

  // header scroll state
  const header=$("#header");
  const onScroll=()=>header.classList.toggle("scrolled",window.scrollY>20);
  onScroll();window.addEventListener("scroll",onScroll,{passive:true});

  // mobile nav
  const burger=$("#burger"),nav=$("#nav");
  burger.addEventListener("click",()=>nav.classList.toggle("open"));
  $$("#nav a").forEach(a=>a.addEventListener("click",()=>nav.classList.remove("open")));

  // reveal + counters via IntersectionObserver
  const io=new IntersectionObserver((entries)=>{
    entries.forEach(en=>{
      if(!en.isIntersecting)return;
      en.target.classList.add("in");
      $$(".stat-num",en.target).forEach(animateCount);
      if(en.target.classList.contains("stat-num"))animateCount(en.target);
      io.unobserve(en.target);
    });
  },{threshold:.15});
  $$(".reveal").forEach(el=>io.observe(el));
  // observe stat numbers directly too
  const statIO=new IntersectionObserver((entries)=>{
    entries.forEach(en=>{if(en.isIntersecting){animateCount(en.target);statIO.unobserve(en.target);}});
  },{threshold:.5});
  $$(".stat-num").forEach(el=>statIO.observe(el));

  // year
  $("#year").textContent=new Date().getFullYear();
});
